#!/bin/bash

red_print(){
        echo -e "\e[1;31m$1\e[0m"
}
green_print(){
        echo -e "\e[1;32m$1\e[0m"
}

# Check if v4l2-ctl exists
if ! command -v v4l2-ctl >/dev/null 2>&1; then
        red_print "v4l2-ctl not found, installing v4l-utils..."
        sudo apt update
        sudo apt install -y v4l-utils
fi

if ! command -v busybox >/dev/null 2>&1; then
        red_print "busybox not found, installing busybox..."
        sudo apt update
        sudo apt install -y busybox
fi
sudo rmmod sgx_gmsl2_cam >/dev/null 2>&1


sudo ./boost_clock.sh >/dev/null 2>&1
sleep 0.5

sudo busybox devmem 0x2448040 w 0x00000003 #for PAC.03,
 
sudo insmod ko/sgx_gmsl2_cam.ko
sudo insmod ko/pwm-gpios.ko >/dev/null 2>&1
 
#For YUV Camera: 1920*1080：sensor_mode=1,1920*1536：sensor_mode=2,3840*2160：sensor_mode=4;For RAW  Camera：sensor_mode=0

#For 6G GMSL2 Mode, set gmsl_mode=0;For 3G GMSL2 Mode(only SG3S11AFSK), set gmsl_mode=1

# trig_pin：
# MAX9296:video0~video5, MAX96712:video6~video9
# MAX9296:  MFP5 - individual trigger, MFP9 - global trigger, MFP10 - MCU trigger
# MAX96712: MFP2 - individual trigger, MFP10 - global trigger, MFP11 - MCU trigger
# Global trigger applies only to external trigger; the MCU provides only the XHS signal for SHW3G.

# Internal Trigger: trigger signal generated by ORIN or MCU
# for shw3g:video0~video5:trig_pin=0x000a0007,video6~video9:trig_pin=0x000b0007;
# for other cameras:video0~video5:trig_pin=0x00050007,video6~video9:trig_pin=0x00020007

# External Trigger: trigger signal generated by signal generator(# Pins 1-4 are individual triggers for DES1-4, Pin 5 is the global trigger, and Pin 6 is GND.)
# for shw3g:video0~video5:trig_pin=0x00090007,video6~video9:trig_pin=0x000a0007;
# for all other cameras:individual triggers:video0~video5:trig_pin=0x00050007,video6~video9:trig_pin=0x00020007;global trigger:video0~video5:trig_pin=0x00090007,video6~video9:trig_pin=0x000a0007

#trig_mode:MASTER_RISE_EDGE:trig_mode=0,SLAVER:trig_mode=2
v4l2-ctl -d /dev/video0 -c sensor_mode=0,gmsl_mode=0,trig_pin=0x00050007,trig_mode=0
v4l2-ctl -d /dev/video1 -c sensor_mode=0,gmsl_mode=0,trig_pin=0x00050007,trig_mode=0
v4l2-ctl -d /dev/video2 -c sensor_mode=0,gmsl_mode=0,trig_pin=0x00050007,trig_mode=0
v4l2-ctl -d /dev/video3 -c sensor_mode=0,gmsl_mode=0,trig_pin=0x00050007,trig_mode=0
v4l2-ctl -d /dev/video4 -c sensor_mode=0,gmsl_mode=0,trig_pin=0x00050007,trig_mode=0
v4l2-ctl -d /dev/video5 -c sensor_mode=0,gmsl_mode=0,trig_pin=0x00050007,trig_mode=0
v4l2-ctl -d /dev/video6 -c sensor_mode=0,gmsl_mode=0,trig_pin=0x00020007,trig_mode=0
v4l2-ctl -d /dev/video7 -c sensor_mode=0,gmsl_mode=0,trig_pin=0x00020007,trig_mode=0
v4l2-ctl -d /dev/video8 -c sensor_mode=0,gmsl_mode=0,trig_pin=0x00020007,trig_mode=0
v4l2-ctl -d /dev/video9 -c sensor_mode=0,gmsl_mode=0,trig_pin=0x00020007,trig_mode=0
